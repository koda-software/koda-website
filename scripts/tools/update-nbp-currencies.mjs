/**
 * Regenerates lib/tools/nbp-currencies.ts from the latest NBP tables A and B.
 *
 * The NBP rate tool must know which table a currency is in before it asks the API:
 * asking table B for a table A code returns stale 2004 data instead of an error.
 * Re-run this every quarter or so, when NBP adds or withdraws a table B currency:
 *
 *   node scripts/tools/update-nbp-currencies.mjs
 */
import fs from "node:fs";
import path from "node:path";

const API = "https://api.nbp.pl/api/exchangerates";
const FIRST = ["EUR", "USD", "GBP", "CHF"];
const target = path.join(process.cwd(), "lib/tools/nbp-currencies.ts");

async function latestTable(table) {
  const response = await fetch(`${API}/tables/${table}/?format=json`);
  if (!response.ok) throw new Error(`Table ${table.toUpperCase()}: HTTP ${response.status}`);
  const [data] = await response.json();
  return data;
}

const byName = (left, right) => left.name.localeCompare(right.name, "pl");

const [tableA, tableB] = await Promise.all([latestTable("a"), latestTable("b")]);
const aCodes = new Set(tableA.rates.map((rate) => rate.code));

const a = tableA.rates.map((rate) => ({ code: rate.code, table: "A", name: rate.currency }));
const b = tableB.rates.filter((rate) => !aCodes.has(rate.code)).map((rate) => ({ code: rate.code, table: "B", name: rate.currency }));

const currencies = [
  ...FIRST.map((code) => a.find((currency) => currency.code === code)).filter(Boolean),
  ...a.filter((currency) => !FIRST.includes(currency.code)).sort(byName),
  ...b.sort(byName),
];

const lines = currencies.map((currency) => `  { code: ${JSON.stringify(currency.code)}, table: "${currency.table}", name: ${JSON.stringify(currency.name)} },`);

const source = `/**
 * Every currency in the NBP average-rate tables, with the table it is published in.
 * Generated by scripts/tools/update-nbp-currencies.mjs from tables ${tableA.no} and ${tableB.no}; do not edit by hand.
 * Names are NBP's own Polish names. Order: EUR, USD, GBP, CHF, then table A by name, then table B by name.
 */
import type { NbpTable } from "./nbp";

export type NbpCurrency = { code: string; table: NbpTable; name: string };

export const nbpCurrencies: NbpCurrency[] = [
${lines.join("\n")}
];
`;

fs.writeFileSync(target, source);
console.log(`Wrote ${currencies.length} currencies (${a.length} in table A, ${b.length} in table B) to ${path.relative(process.cwd(), target)}`);
